// Method Primitive

// - String
let nama = "Renuy";
console.log(nama);
console.log(nama.toUpperCase());
console.log(nama.toLowerCase());

// - Number
let angka = 123.12312312312;
console.log(angka);
console.log(angka.toFixed());
console.log(typeof angka.toString());

// -. Boolean
let isTrue = true;
console.log(isTrue);
console.log(isTrue.valueOf() === false);

