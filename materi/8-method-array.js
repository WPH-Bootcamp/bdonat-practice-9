// Method Array
/*
    1. push() -> Menambahkan elemen array dari paling akhir index
    2. pop() -> Menghapus elemen array dari paling akhir index
    3. shift() -> Menghapus elemen pertama dari array dan mengembalikannya.
    4. unshift() -> Menambahkan elemen di awal elemen array 
*/

let buah = ["Jeruk", "Mangga", "Jamblang", "Cherry", "Blue Berry"];
console.log(buah);

// -. push()
buah.push("Delima");
console.log(buah);

// -. pop()
buah.pop();
console.log(buah);

// -. shift()
buah.shift();
console.log(buah);

// -. unshift()
buah.unshift("Nagha");
console.log(buah);
